    s.push_str("@keyframes slide-down{from{transform:translateY(-10px);opacity:0;}to{transform:translateY(0);opacity:1;}}");
    s.push_str("@keyframes drawer-up{from{transform:translateY(100%);}to{transform:translateY(0);}}");

